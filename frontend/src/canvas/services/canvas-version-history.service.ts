// 🗄️ Canvas版本历史记录服务 - 本地存储历史版本管理
// 提供画布历史版本的保存、加载、管理功能，支持循环存储策略
// 注意：此服务与canvas-history.service.ts不同，后者用于撤销/重做，此服务用于版本历史管理

import type { Canvas } from '../types/canvas';
import { DEFAULT_CANVAS_TITLE } from '@/canvas/constants';
import { debugLog } from '../utils/devLogger';
// Simple localStorage wrapper to replace local-db.service
const localDbService = {
  set: (key: string, value: any) => {
    localStorage.setItem(key, JSON.stringify(value));
  },
  get: <T>(key: string): T | null => {
    const item = localStorage.getItem(key);
    return item ? JSON.parse(item) : null;
  },
  remove: (key: string) => {
    localStorage.removeItem(key);
  },
  getAllKeys: (): string[] => {
    return Object.keys(localStorage);
  }
};
import { validateCanvas, getCurrentTimestamp, generateId } from '../utils/canvasUtils';

// 📋 历史版本接口定义
export interface CanvasHistory {
  id: string;
  title: string;
  canvas: Canvas;
  timestamp: number;
  autoGenerated: boolean;
}

export interface HistoryStore {
  histories: CanvasHistory[];
  currentIndex: number;
}

// 🛠️ 版本历史服务接口
export interface VersionHistoryService {
  // 核心操作
  saveToHistory(canvas: Canvas): Promise<void>;
  getHistoryList(): CanvasHistory[];
  loadHistory(id: string): Canvas | null;
  deleteHistory(id: string): boolean;
  clearHistory(): void;
  
  // 工具方法
  getHistoryCount(): number;
  getHistoryStats(): HistoryStats;
  canSave(canvas: Canvas): boolean;
  
  // 防抖保存
  debouncedSave(canvas: Canvas): void;
}

// 📊 历史统计信息
export interface HistoryStats {
  total: number;
  autoGenerated: number;
  manualSaved: number;
  oldestTimestamp: number;
  newestTimestamp: number;
  storageSize: number; // 估算的存储大小（字节）
}

// ⚙️ 配置常量
const HISTORY_CONFIG = {
  MAX_HISTORIES: 20,              // 最大保存20个历史版本
  STORAGE_KEY: 'canvas_version_history',  // LocalStorage存储键（与撤销历史区分）
  DEBOUNCE_DELAY: 500,           // 防抖延迟500ms
  AUTO_SAVE_THRESHOLD: 1000,     // 自动保存阈值（变化程度）
} as const;

class CanvasVersionHistoryServiceImpl implements VersionHistoryService {
  private debounceTimer: number | null = null;
  private lastSavedHash: string | null = null;

  // 📝 保存画布到历史记录
  async saveToHistory(canvas: Canvas): Promise<void> {
    try {
      // 验证画布数据有效性
      if (!validateCanvas(canvas)) {
        console.warn('[VersionHistoryService] 无效的Canvas数据，跳过保存');
        return;
      }

      // 检查是否可以保存（避免重复保存相同内容）
      if (!this.canSave(canvas)) {
        debugLog('[VersionHistoryService] 内容未变化，跳过保存');
        return;
      }

      const currentStore = this.getHistoryStore();
      const now = getCurrentTimestamp();
      
      // 创建新的历史记录
      const isUntitled = !canvas.title || canvas.title.trim() === '' || canvas.title === 'Untitled Canvas' || canvas.title === DEFAULT_CANVAS_TITLE;
      const newHistory: CanvasHistory = {
        id: generateId(),
        title: this.generateHistoryTitle(canvas),
        canvas: this.deepCloneCanvas(canvas), // 深拷贝画布数据
        timestamp: now,
        autoGenerated: isUntitled
      };

      // 添加到历史列表（头部插入）
      const updatedHistories = [newHistory, ...currentStore.histories];

      // 应用循环存储策略（保持最多20个）
      if (updatedHistories.length > HISTORY_CONFIG.MAX_HISTORIES) {
        updatedHistories.splice(HISTORY_CONFIG.MAX_HISTORIES);
      }

      // 保存更新后的历史存储
      const updatedStore: HistoryStore = {
        histories: updatedHistories,
        currentIndex: 0 // 当前索引指向最新的记录
      };

      localDbService.set(HISTORY_CONFIG.STORAGE_KEY, updatedStore);
      
      // 更新最后保存的哈希值
      this.lastSavedHash = this.calculateCanvasHash(canvas);
      
      debugLog(`[VersionHistoryService] 成功保存历史版本: ${newHistory.title} (ID: ${newHistory.id})`);
      
    } catch (error) {
      console.error('[VersionHistoryService] 保存历史版本失败:', error);
      throw new Error(`历史版本保存失败: ${error instanceof Error ? error.message : '未知错误'}`);
    }
  }

  // 📋 获取历史记录列表（按时间倒序）
  getHistoryList(): CanvasHistory[] {
    try {
      const store = this.getHistoryStore();
      return [...store.histories]; // 返回副本避免意外修改
    } catch (error) {
      console.error('[VersionHistoryService] 获取历史记录列表失败:', error);
      return [];
    }
  }

  // 📂 加载指定历史记录
  loadHistory(id: string): Canvas | null {
    try {
      const store = this.getHistoryStore();
      const history = store.histories.find(h => h.id === id);
      
      if (!history) {
        console.warn(`[VersionHistoryService] 未找到历史版本: ${id}`);
        return null;
      }

      // 验证历史记录中的画布数据
      if (!validateCanvas(history.canvas)) {
        console.warn(`[VersionHistoryService] 历史版本中的画布数据无效: ${id}`);
        return null;
      }

      debugLog(`[VersionHistoryService] 成功加载历史版本: ${history.title} (${new Date(history.timestamp).toISOString()})`);
      
      // 返回画布数据的副本
      return this.deepCloneCanvas(history.canvas);
      
    } catch (error) {
      console.error(`[VersionHistoryService] 加载历史版本失败 [${id}]:`, error);
      return null;
    }
  }

  // 🗑️ 删除指定历史记录
  deleteHistory(id: string): boolean {
    try {
      const store = this.getHistoryStore();
      const initialCount = store.histories.length;
      
      // 过滤掉指定ID的历史记录
      const filteredHistories = store.histories.filter(h => h.id !== id);
      
      if (filteredHistories.length === initialCount) {
        console.warn(`[VersionHistoryService] 未找到要删除的历史版本: ${id}`);
        return false;
      }

      // 更新存储
      const updatedStore: HistoryStore = {
        histories: filteredHistories,
        currentIndex: Math.max(0, store.currentIndex - 1) // 调整当前索引
      };

      localDbService.set(HISTORY_CONFIG.STORAGE_KEY, updatedStore);
      
      debugLog(`[VersionHistoryService] 成功删除历史版本: ${id}`);
      return true;
      
    } catch (error) {
      console.error(`[VersionHistoryService] 删除历史版本失败 [${id}]:`, error);
      return false;
    }
  }

  // 🧹 清空所有历史记录
  clearHistory(): void {
    try {
      const emptyStore: HistoryStore = {
        histories: [],
        currentIndex: 0
      };

      localDbService.set(HISTORY_CONFIG.STORAGE_KEY, emptyStore);
      this.lastSavedHash = null;
      
      debugLog('[VersionHistoryService] 成功清空所有历史版本');
      
    } catch (error) {
      console.error('[VersionHistoryService] 清空历史版本失败:', error);
      throw new Error(`清空历史版本失败: ${error instanceof Error ? error.message : '未知错误'}`);
    }
  }

  // 📊 获取历史记录数量
  getHistoryCount(): number {
    return this.getHistoryStore().histories.length;
  }

  // 📈 获取历史统计信息
  getHistoryStats(): HistoryStats {
    try {
      const histories = this.getHistoryList();
      
      if (histories.length === 0) {
        return {
          total: 0,
          autoGenerated: 0,
          manualSaved: 0,
          oldestTimestamp: 0,
          newestTimestamp: 0,
          storageSize: 0
        };
      }

      const autoGenerated = histories.filter(h => h.autoGenerated).length;
      const manualSaved = histories.length - autoGenerated;
      const timestamps = histories.map(h => h.timestamp);
      
      // 估算存储大小
      const storageSize = this.estimateStorageSize(histories);

      return {
        total: histories.length,
        autoGenerated,
        manualSaved,
        oldestTimestamp: Math.min(...timestamps),
        newestTimestamp: Math.max(...timestamps),
        storageSize
      };
      
    } catch (error) {
      console.error('[VersionHistoryService] 获取历史统计失败:', error);
      return {
        total: 0,
        autoGenerated: 0,
        manualSaved: 0,
        oldestTimestamp: 0,
        newestTimestamp: 0,
        storageSize: 0
      };
    }
  }

  // ✅ 检查是否可以保存（避免重复保存）
  canSave(canvas: Canvas): boolean {
    try {
      const currentHash = this.calculateCanvasHash(canvas);
      
      // 如果内容没有变化，则不需要保存
      if (this.lastSavedHash === currentHash) {
        return false;
      }

      // 检查是否与最近的历史记录相同
      const recentHistories = this.getHistoryList().slice(0, 3);
      for (const history of recentHistories) {
        const historyHash = this.calculateCanvasHash(history.canvas);
        if (historyHash === currentHash) {
          return false;
        }
      }

      return true;
    } catch (error) {
      console.warn('[VersionHistoryService] 检查保存条件时出错:', error);
      return true; // 出错时默认允许保存
    }
  }

  // ⏰ 防抖保存（避免频繁保存）
  debouncedSave(canvas: Canvas): void {
    // 清除之前的定时器
    if (this.debounceTimer !== null) {
      clearTimeout(this.debounceTimer);
    }

    // 设置新的定时器
    this.debounceTimer = window.setTimeout(() => {
      this.saveToHistory(canvas).catch(error => {
        console.error('[VersionHistoryService] 防抖保存失败:', error);
      });
      this.debounceTimer = null;
    }, HISTORY_CONFIG.DEBOUNCE_DELAY);
  }

  // 🔧 私有方法：获取历史存储数据
  private getHistoryStore(): HistoryStore {
    try {
      const store = localDbService.get<HistoryStore>(HISTORY_CONFIG.STORAGE_KEY);
      
      if (!store) {
        // 返回空的历史存储
        return {
          histories: [],
          currentIndex: 0
        };
      }

      // 验证数据结构
      if (!Array.isArray(store.histories)) {
        console.warn('[VersionHistoryService] 历史存储数据结构异常，重置为空');
        return {
          histories: [],
          currentIndex: 0
        };
      }

      return store;
    } catch (error) {
      console.error('[VersionHistoryService] 获取历史存储失败:', error);
      return {
        histories: [],
        currentIndex: 0
      };
    }
  }

  // 🏷️ 生成历史记录标题
  private generateHistoryTitle(canvas: Canvas): string {
    if (canvas.title && canvas.title.trim() !== '' && !['无标题画布', 'Untitled Canvas', DEFAULT_CANVAS_TITLE].includes(canvas.title)) {
      return canvas.title;
    }

    // 自动生成标题
    const nodeCount = canvas.nodes.length;
    const connectionCount = canvas.connections.length;
    const timestamp = new Intl.DateTimeFormat(undefined, {
      hour: '2-digit',
      minute: '2-digit'
    }).format(new Date());

    if (nodeCount === 0) {
      return `空画布 ${timestamp}`;
    }

    const nodeTypes = canvas.nodes.reduce((acc, node) => {
      acc[node.type] = (acc[node.type] || 0) + 1;
      return acc;
    }, {} as Record<string, number>);

    const typeDescriptions: string[] = [];
    if (nodeTypes.text) typeDescriptions.push(`${nodeTypes.text}个文本`);
    if (nodeTypes.code) typeDescriptions.push(`${nodeTypes.code}个代码`);
    if (nodeTypes.column) typeDescriptions.push(`${nodeTypes.column}个容器`);
    if (nodeTypes.table) typeDescriptions.push(`${nodeTypes.table}个表格`);

    const description = typeDescriptions.join('、');
    return `${description} ${timestamp}`;
  }

  // 🔧 计算画布内容哈希（用于重复检测）
  private calculateCanvasHash(canvas: Canvas): string {
    try {
      // 提取关键信息用于哈希计算
      const hashData = {
        nodes: canvas.nodes.map(node => ({
          type: node.type,
          content: node.content,
          x: Math.round(node.x / 10) * 10, // 降低位置精度，避免微小移动导致不同哈希
          y: Math.round(node.y / 10) * 10,
          width: node.width,
          height: node.height,
          title: node.title,
          codeType: node.codeType
        })),
        connections: canvas.connections.map(conn => ({
          from: conn.from,
          to: conn.to,
          label: conn.label
        })),
        title: canvas.title
      };

      // 简单哈希算法
      const str = JSON.stringify(hashData);
      let hash = 0;
      for (let i = 0; i < str.length; i++) {
        const char = str.charCodeAt(i);
        hash = ((hash << 5) - hash) + char;
        hash = hash & hash; // 转换为32位整数
      }
      return hash.toString(36);
    } catch (error) {
      console.warn('[VersionHistoryService] 计算画布哈希失败:', error);
      return Date.now().toString(36); // 降级方案
    }
  }

  // 📏 估算存储大小
  private estimateStorageSize(histories: CanvasHistory[]): number {
    try {
      const jsonString = JSON.stringify(histories);
      return jsonString.length * 2; // Unicode字符约2字节
    } catch (error) {
      console.warn('[VersionHistoryService] 估算存储大小失败:', error);
      return 0;
    }
  }

  // 🔄 深拷贝画布对象
  private deepCloneCanvas(canvas: Canvas): Canvas {
    try {
      return JSON.parse(JSON.stringify(canvas));
    } catch (error) {
      console.error('[VersionHistoryService] 深拷贝画布失败:', error);
      throw new Error('画布数据深拷贝失败');
    }
  }
}

// 🏭 单例模式导出
export const canvasVersionHistoryService: VersionHistoryService = new CanvasVersionHistoryServiceImpl();

// 📦 便捷函数导出
export const {
  saveToHistory,
  getHistoryList,
  loadHistory,
  deleteHistory,
  clearHistory,
  getHistoryCount,
  getHistoryStats,
  canSave,
  debouncedSave
} = canvasVersionHistoryService;
