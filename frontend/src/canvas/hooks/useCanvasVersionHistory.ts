// 🎯 Canvas版本历史记录 Hook
// 提供在React组件中使用版本历史功能的便捷接口

import { useState, useCallback, useEffect, useRef } from 'react';
import type { Canvas } from '../../types/canvas';
import { 
  canvasVersionHistoryService,
  CanvasHistory, 
  HistoryStats 
} from '../services/canvas-version-history.service';

export interface UseCanvasVersionHistoryOptions {
  autoSave?: boolean;           // 是否自动保存（默认true）
  autoSaveDelay?: number;       // 自动保存延迟时间（默认500ms）
  maxHistories?: number;        // 最大历史记录数（只读，实际由service控制）
}

export interface UseCanvasVersionHistoryReturn {
  // 历史记录数据
  histories: CanvasHistory[];
  historyStats: HistoryStats;
  isLoading: boolean;
  error: string | null;
  
  // 操作方法
  saveToHistory: (canvas: Canvas) => Promise<void>;
  loadHistory: (id: string) => Canvas | null;
  deleteHistory: (id: string) => boolean;
  clearAllHistory: () => void;
  refreshHistories: () => void;
  
  // 防抖保存
  debouncedSaveToHistory: (canvas: Canvas) => void;
  
  // 工具方法
  canSave: (canvas: Canvas) => boolean;
  getHistoryCount: () => number;
}

/**
 * Canvas版本历史记录Hook
 * 
 * @param options 配置选项
 * @returns 历史记录状态和操作方法
 * 
 * @example
 * ```tsx
 * const {
 *   histories,
 *   historyStats,
 *   saveToHistory,
 *   loadHistory,
 *   deleteHistory,
 *   debouncedSaveToHistory
 * } = useCanvasVersionHistory({
 *   autoSave: true,
 *   autoSaveDelay: 500
 * });
 * 
 * // 保存当前画布到历史
 * const handleSave = async () => {
 *   try {
 *     await saveToHistory(currentCanvas);
 *     console.log('保存成功');
 *   } catch (error) {
 *     console.error('保存失败:', error);
 *   }
 * };
 * 
 * // 加载历史版本
 * const handleLoadHistory = (historyId: string) => {
 *   const canvas = loadHistory(historyId);
 *   if (canvas) {
 *     setCurrentCanvas(canvas);
 *   }
 * };
 * ```
 */
export function useCanvasVersionHistory(
  options: UseCanvasVersionHistoryOptions = {}
): UseCanvasVersionHistoryReturn {
  const {
    autoSave = true,
    autoSaveDelay = 500,
  } = options;

  // 状态管理
  const [histories, setHistories] = useState<CanvasHistory[]>([]);
  const [historyStats, setHistoryStats] = useState<HistoryStats>({
    total: 0,
    autoGenerated: 0,
    manualSaved: 0,
    oldestTimestamp: 0,
    newestTimestamp: 0,
    storageSize: 0
  });
  const [isLoading, setIsLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  // 防抖计时器引用
  const debounceTimerRef = useRef<number | null>(null);

  // 🔄 刷新历史记录列表
  const refreshHistories = useCallback(() => {
    try {
      setIsLoading(true);
      setError(null);
      
      const historyList = canvasVersionHistoryService.getHistoryList();
      const stats = canvasVersionHistoryService.getHistoryStats();
      
      setHistories(historyList);
      setHistoryStats(stats);
    } catch (err) {
      const errorMessage = err instanceof Error ? err.message : '刷新历史记录失败';
      setError(errorMessage);
      console.error('[useCanvasVersionHistory] 刷新历史记录失败:', err);
    } finally {
      setIsLoading(false);
    }
  }, []);

  // 💾 保存到历史记录
  const saveToHistory = useCallback(async (canvas: Canvas) => {
    try {
      setIsLoading(true);
      setError(null);
      
      await canvasVersionHistoryService.saveToHistory(canvas);
      
      // 保存成功后刷新列表
      refreshHistories();
      
    } catch (err) {
      const errorMessage = err instanceof Error ? err.message : '保存历史版本失败';
      setError(errorMessage);
      console.error('[useCanvasVersionHistory] 保存失败:', err);
      throw err; // 重新抛出错误供调用者处理
    } finally {
      setIsLoading(false);
    }
  }, [refreshHistories]);

  // 📂 加载历史记录
  const loadHistory = useCallback((id: string): Canvas | null => {
    try {
      setError(null);
      return canvasVersionHistoryService.loadHistory(id);
    } catch (err) {
      const errorMessage = err instanceof Error ? err.message : '加载历史版本失败';
      setError(errorMessage);
      console.error('[useCanvasVersionHistory] 加载失败:', err);
      return null;
    }
  }, []);

  // 🗑️ 删除历史记录
  const deleteHistory = useCallback((id: string): boolean => {
    try {
      setError(null);
      const success = canvasVersionHistoryService.deleteHistory(id);
      
      if (success) {
        // 删除成功后刷新列表
        refreshHistories();
      }
      
      return success;
    } catch (err) {
      const errorMessage = err instanceof Error ? err.message : '删除历史版本失败';
      setError(errorMessage);
      console.error('[useCanvasVersionHistory] 删除失败:', err);
      return false;
    }
  }, [refreshHistories]);

  // 🧹 清空所有历史记录
  const clearAllHistory = useCallback(() => {
    try {
      setError(null);
      canvasVersionHistoryService.clearHistory();
      
      // 清空成功后刷新列表
      refreshHistories();
    } catch (err) {
      const errorMessage = err instanceof Error ? err.message : '清空历史记录失败';
      setError(errorMessage);
      console.error('[useCanvasVersionHistory] 清空失败:', err);
    }
  }, [refreshHistories]);

  // ⏰ 防抖保存
  const debouncedSaveToHistory = useCallback((canvas: Canvas) => {
    if (!autoSave) {
      return;
    }

    // 清除之前的定时器
    if (debounceTimerRef.current !== null) {
      clearTimeout(debounceTimerRef.current);
    }

    // 设置新的定时器
    debounceTimerRef.current = window.setTimeout(() => {
      saveToHistory(canvas).catch(error => {
        console.error('[useCanvasVersionHistory] 防抖保存失败:', error);
      });
      debounceTimerRef.current = null;
    }, autoSaveDelay);
  }, [autoSave, autoSaveDelay, saveToHistory]);

  // ✅ 检查是否可以保存
  const canSave = useCallback((canvas: Canvas): boolean => {
    try {
      return canvasVersionHistoryService.canSave(canvas);
    } catch (err) {
      console.warn('[useCanvasVersionHistory] 检查保存条件失败:', err);
      return true; // 出错时默认允许保存
    }
  }, []);

  // 📊 获取历史记录数量
  const getHistoryCount = useCallback((): number => {
    return canvasVersionHistoryService.getHistoryCount();
  }, []);

  // 🎯 组件挂载时初始化
  useEffect(() => {
    refreshHistories();
  }, [refreshHistories]);

  // 🧹 组件卸载时清理定时器
  useEffect(() => {
    return () => {
      if (debounceTimerRef.current !== null) {
        clearTimeout(debounceTimerRef.current);
        debounceTimerRef.current = null;
      }
    };
  }, []);

  return {
    // 状态数据
    histories,
    historyStats,
    isLoading,
    error,
    
    // 操作方法
    saveToHistory,
    loadHistory,
    deleteHistory,
    clearAllHistory,
    refreshHistories,
    
    // 防抖保存
    debouncedSaveToHistory,
    
    // 工具方法
    canSave,
    getHistoryCount,
  };
}